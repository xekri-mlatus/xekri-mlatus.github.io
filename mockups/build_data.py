"""Build mockups/notes.js: every note's metadata and rendered text, for the page mockups.

Hugo renders the notes (shortcodes and all) into a temporary folder; this script
takes each note's content from there and points its images and links at the
mockup pages. Run it from the repository root after notes change:

    python mockups/build_data.py
"""
import html
import json
import re
import subprocess
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
NOTES = ROOT / "content" / "notes"
OUT = ROOT / "mockups" / "notes.js"
SITE = "https://xekri-mlatus.github.io"


def front_matter(path):
    text = path.read_text(encoding="utf-8")
    _, fm, _ = text.split("---\n", 2)
    return yaml.safe_load(fm)


def hashtag(tag):
    return tag.lower().replace(" ", "")


def main():
    with tempfile.TemporaryDirectory() as build:
        subprocess.run(["hugo", "--quiet", "-d", build], cwd=ROOT, check=True)
        notes = []
        for path in sorted(NOTES.glob("*/index.md")) + sorted(NOTES.glob("*.md")):
            if path.name == "_index.md":
                continue
            fm = front_matter(path)
            folder = path.parent.name if path.name == "index.md" else None
            slug = fm["slug"]
            page = (Path(build) / "notes" / slug / "index.html").read_text(encoding="utf-8")
            # The content div ends before the footer, or before the old-note aside on old notes.
            m = re.search(r'<div class="post-content md-content">(.*?)\n  </div>\n(?:<aside|\n\n  <footer)', page, re.S)
            body = m.group(1).strip() if m else ""

            # Images: Markdown ones come out as /notes/<slug>/x.jpg, figures as x.jpg.
            def img(m):
                name = m.group(2).rsplit("/", 1)[-1]
                return f'{m.group(1)}../content/notes/{folder}/{name}"'
            body = re.sub(r'(<img[^>]*?\ssrc=")([^"]+)"', img, body)
            body = re.sub(r'\sloading="lazy"', "", body)
            # Links to other notes open their mockup page.
            body = re.sub(r'href="(?:' + re.escape(SITE) + r')?/notes/([^/"]+)/"', r'href="note.html?slug=\1"', body)

            text = html.unescape(re.sub(r"<[^>]+>", " ", body))
            text = re.sub(r"\s+", " ", text).strip()
            # Image descriptions, so search finds memes that have no text of their own.
            alts = [html.unescape(a) for a in re.findall(r'<img[^>]*?\salt="([^"]*)"', body) if a.strip()]
            cover = (fm.get("cover") or {}).get("image")
            first = re.search(r'<img[^>]*?\ssrc="([^"]+)"', body)
            thumb = f"../content/notes/{folder}/{cover}" if cover and folder else (first.group(1) if first else None)
            date = fm["date"]
            notes.append({
                "slug": slug,
                "title": fm["title"],
                "date": date.isoformat() if hasattr(date, "isoformat") else str(date),
                "tags": [hashtag(t) for t in fm.get("tags") or []],
                "html": body,
                "text": text,
                "alts": alts,
                "thumb": thumb,
            })
    notes.sort(key=lambda n: n["date"], reverse=True)
    OUT.write_text("// Generated by build_data.py — don't edit by hand.\nwindow.NOTES = "
                   + json.dumps(notes, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print(f"{len(notes)} notes -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
